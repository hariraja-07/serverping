-- Initial schema for serverping: target (the thing watched) and target_check (one row per
-- probe — the history that survives a restart, since Target only holds the latest result).
--
-- HOW THIS FILE WAS AUTHORED
-- Not hand-written from the entities. Hibernate was pointed at an empty PostgreSQL 17 with
-- ddl-auto=update, then `pg_dump --schema-only` captured the DDL it produced, and those
-- statements are transcribed here. That matters because ddl-auto=validate compares the live
-- schema against what Hibernate expects, and guessing which JDBC type an Instant maps to
-- (`timestamp(6)` vs `timestamp(6) with time zone`) is exactly how you end up debugging a
-- type mismatch at startup instead of shipping.
--
-- Three deliberate departures from the raw dump:
--   * pg_dump's session preamble dropped — SET/client_encoding and friends are psql plumbing,
--     not schema.
--   * `\restrict` / `\unrestrict` dropped — psql meta-commands that Flyway cannot execute and
--     would fail on the very first migration.
--   * `ALTER TABLE ... OWNER TO serverping` dropped — the owner must be whoever runs Flyway.
--     Hardcoding a role makes the migration fail outright when deployed under a different user.
--
-- No foreign key from target_check.target_id to target.id on purpose: history outlives the
-- target it belongs to, so deleting a target must not delete its check rows.

CREATE TABLE public.target (
    id bigint NOT NULL,
    consecutive_fails integer NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    enabled boolean NOT NULL,
    host character varying(255) NOT NULL,
    interval_seconds integer NOT NULL,
    last_checked_at timestamp(6) with time zone,
    latency_ms bigint,
    name character varying(100) NOT NULL,
    port integer NOT NULL,
    protocol character varying(16) NOT NULL,
    status character varying(16) NOT NULL,
    CONSTRAINT target_protocol_check CHECK (((protocol)::text = 'TCP'::text)),
    CONSTRAINT target_status_check CHECK (((status)::text = ANY ((ARRAY['UP'::character varying, 'DOWN'::character varying, 'UNKNOWN'::character varying])::text[])))
);

CREATE TABLE public.target_check (
    id bigint NOT NULL,
    checked_at timestamp(6) with time zone NOT NULL,
    detail character varying(64),
    latency_ms bigint NOT NULL,
    status character varying(16) NOT NULL,
    target_id bigint NOT NULL,
    CONSTRAINT target_check_status_check CHECK (((status)::text = ANY ((ARRAY['UP'::character varying, 'DOWN'::character varying, 'UNKNOWN'::character varying])::text[])))
);

-- Identity, so ids come from the database rather than a table the app has to remember to own.
ALTER TABLE public.target_check ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.target_check_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE public.target ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.target_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.target_check
    ADD CONSTRAINT target_check_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.target
    ADD CONSTRAINT target_pkey PRIMARY KEY (id);
